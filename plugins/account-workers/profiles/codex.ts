export function unsupportedLayers(home: string): string[] {
  return [
    "/etc/codex/config.toml",
    "/etc/codex/managed_config.toml",
    "/etc/codex/requirements.toml",
    path.join(home, "managed_config.toml"),
    path.join(home, "requirements.toml"),
  ];
}

const SERVER_NAME = /^[A-Za-z0-9_-]{1,64}$/;
export const HEARTBEAT_MAX_AGE_MS = EXEC_MAX_TIMEOUT_MS + 5 * 60_000;

const q = (value: string) => JSON.stringify(value);

export function codexHome(env: NodeJS.ProcessEnv = process.env): string {
  return env.CODEX_HOME && path.isAbsolute(env.CODEX_HOME) ? env.CODEX_HOME : path.join(homedir(), ".codex");
}

function errorCode(error: unknown): string | undefined {
  return (error as NodeJS.ErrnoException | null)?.code;
}

async function readText(file: string): Promise<string | null> {
  try {
    return await readFile(file, "utf8");
  } catch (error) {
    if (errorCode(error) === "ENOENT") return null;
    throw error;
  }
}

export function parseToml(text: string, what: string): TomlTable {
  try {
    return parse(text) as TomlTable;
  } catch (error) {
    throw new WorkspaceRefusal(`${what} is not valid TOML: ${(error as Error).message.split("\n")[0]}`);
  }
}

export async function readUserConfig(home: string): Promise<TomlTable> {
  const text = await readText(path.join(home, "config.toml"));
  return text === null ? {} : parseToml(text, "the worker's Codex config.toml");
}

function table(value: unknown): TomlTable {
  return value !== null && typeof value === "object" && !Array.isArray(value) ? (value as TomlTable) : {};
}

export function mcpServerNames(config: TomlTable): string[] {
  const names = Object.keys(table(config.mcp_servers));
  const bad = names.filter((name) => !SERVER_NAME.test(name));
  if (bad.length > 0) throw new WorkspaceRefusal(`unsupported Codex MCP server name ${q(bad[0]!)}`);
  return names;
}

export function overlayToml(mcpNames: readonly string[]): string {
  const lines = [
    "# Generated by the account-workers plugin: Codex acts only through the workspace tools.",
    'web_search = "disabled"',
    "",
    "[features]",
    ...CODEX_FEATURES_ON.map((feature) => `${feature} = true`),
    ...CODEX_FEATURES_OFF.map((feature) => `${feature} = false`),
  ];
  for (const name of mcpNames) lines.push("", `[mcp_servers.${q(name)}]`, "enabled = false");
  return `${lines.join("\n")}\n`;
}

export function heartbeatDir(scratchDir: string): string {
  return path.join(scratchDir, ".aw", "hb");
}

export function verifiedFile(scratchDir: string): string {
  return path.join(scratchDir, ".aw", "verified.jsonl");
}

export function gateFile(scratchDir: string): string {
  return path.join(scratchDir, ".aw", "gate.json");
}

export function hookCommand(scratchDir: string): string {
  return `sh '${path.join(scratchDir, ".codex", "aw-guard.sh")}'`;
}

export function hooksJson(scratchDir: string): string {
  const hooks = { PreToolUse: [{ matcher: "*", hooks: [{ type: "command", command: hookCommand(scratchDir) }] }] };
  return `${JSON.stringify({ hooks }, null, 2)}\n`;
}

export function expectedTrustKey(scratchDir: string): string {
  return `${path.join(scratchDir, ".codex", "hooks.json")}:pre_tool_use:0:0`;
}

export function codexGuardScript(allowed: readonly string[], heartbeatTools: readonly string[], heartbeat: string): string {
  return `// Generated by the account-workers plugin. Blocks every tool not listed.
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
const allowed = new Set(${JSON.stringify(allowed)});
const recorded = new Set(${JSON.stringify(heartbeatTools)});
const block = (reason) => {
  process.stderr.write(reason + "\\n");
  process.exit(2);
};
process.on("uncaughtException", () => block("account-workers guard failed; tool blocked"));
let input = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => (input += chunk));
process.stdin.on("end", () => {
  let call;
  try {
    call = JSON.parse(input);
  } catch {
    block("account-workers guard could not read the tool call; tool blocked");
  }
  const name = call?.tool_name;
  if (typeof name === "string" && allowed.has(name)) {
    if (recorded.has(name)) {
      try {
        const t = Date.now();
        writeFileSync(${q(heartbeat)} + "/" + t + "-" + randomBytes(8).toString("hex") + ".json", JSON.stringify({ tool_name: name, tool_input: call.tool_input ?? null, tool_use_id: String(call.tool_use_id ?? ""), t }), { flag: "wx" });
      } catch {
        block("account-workers guard could not record the call; tool blocked");
      }
    }
    process.exit(0);
  }
  block(
    "Tool " + String(name) + " is disabled in this thread: it would act on the worker machine. " +
      "Use the workspace_* tools, which act on the bound workspace.",
  );
});
`;
}

function nodeForGuard(): string {
  return /^node(\.exe)?$/.test(path.basename(process.execPath)) ? process.execPath : "";
}

export function codexAllowed(toolNames: readonly string[]): string[] {
  return [...toolNames, ...CODEX_EXTRA_ALLOWED];
}

export function codexFiles(scratchDir: string, toolNames: readonly string[], mcpNames: readonly string[], nodePath = nodeForGuard()) {
  if (scratchDir.includes("'")) throw new WorkspaceRefusal("scratch path contains a quote");
  return [
    { path: ".codex/config.toml", content: overlayToml(mcpNames) },
    { path: ".codex/hooks.json", content: hooksJson(scratchDir) },
    { path: ".codex/aw-guard.mjs", content: codexGuardScript(codexAllowed(toolNames), toolNames, heartbeatDir(scratchDir)) },
    { path: ".codex/aw-guard.sh", content: guardLauncher(nodePath), mode: 0o755 },
  ];
}


export interface HookTrust {
  key: string;
  hash: string;
}

function trustText(scratchDir: string, trust: HookTrust): string[] {
  return [
    `[projects.${q(scratchDir)}]`,
    'trust_level = "trusted"',
    "",
    `[hooks.state.${q(trust.key)}]`,
    `trusted_hash = ${q(trust.hash)}`,
  ];
}

export function hasTrust(config: TomlTable, scratchDir: string, trust: HookTrust): boolean {
  const project = table(table(config.projects)[scratchDir]);
  const hook = table(table(table(config.hooks).state)[trust.key]);
  return project.trust_level === "trusted" && hook.trusted_hash === trust.hash;
}

export function addTrustText(before: string, scratchDir: string, trust: HookTrust): string {
  const sep = before === "" || before.endsWith("\n") ? "" : "\n";
  return `${before}${sep}\n${trustText(scratchDir, trust).join("\n")}\n`;
}

function keyPath(line: string): string[] | null {
  let value: unknown;
  try {
    value = parse(line);
  } catch {
    return null;
  }
  const out: string[] = [];
  while (value !== null && typeof value === "object" && !Array.isArray(value)) {
    const keys = Object.keys(value as TomlTable);
    if (keys.length !== 1) break;
    out.push(keys[0]!);
    value = (value as TomlTable)[keys[0]!];
  }
  return out;
}

const samePath = (a: readonly string[] | null, b: readonly string[]) => a !== null && a.length === b.length && a.every((k, i) => k === b[i]);

export function removeTrustText(before: string, scratchDir: string, trust: HookTrust): string {
  const targets = [
    { table: ["projects", scratchDir], key: "trust_level" },
    { table: ["hooks", "state", trust.key], key: "trusted_hash" },
  ];
  const sections: { header: string | null; body: string[] }[] = [{ header: null, body: [] }];
  for (const line of before.split("\n")) {
    const trimmed = line.trim();
    if (trimmed.startsWith("[")) sections.push({ header: line, body: [] });
    else sections.at(-1)!.body.push(line);
  }
  const out: string[] = [];
  for (const section of sections) {
    const headerPath = section.header !== null && !section.header.trim().startsWith("[[") ? keyPath(section.header) : null;
    const target = targets.find((t) => samePath(headerPath, t.table));
    if (target === undefined) {
      if (section.header !== null) out.push(section.header);
      out.push(...section.body);
      continue;
    }
    const body = section.body.filter((line) => !samePath(keyPath(line), [target.key]));
    const keepsKeys = body.some((line) => line.trim() !== "" && !line.trim().startsWith("#"));
    if (keepsKeys) {
      out.push(section.header!, ...body);
      continue;
    }
    if (out.length > 0 && out.at(-1)!.trim() === "") out.pop();
    out.push(...body);
  }
  return out.join("\n");
}

async function configTarget(home: string): Promise<string> {
  const file = path.join(home, "config.toml");
  try {
    return await realpath(file);
  } catch (error) {
    if (errorCode(error) === "ENOENT") return file;
    throw error;
  }
}

export function editCodexConfig(
  home: string,
  edit: (before: string) => string,
  accept: (config: TomlTable) => boolean,
): Promise<void> {
  return serialized("codex-config", async () => {
    const file = await configTarget(home);
    for (let attempt = 0; attempt < 3; attempt++) {
      const before = await readText(file);
      if (before === null) await stat(home).catch(() => {
        throw new WorkspaceRefusal(`Codex home ${home} does not exist on the worker`);
      });
      const next = edit(before ?? "");
      if (!accept(parseToml(next, "the edited Codex config.toml"))) {
        throw new WorkspaceRefusal("the edited Codex config.toml did not read back as intended; not written");
      }
      const mode = before === null ? 0o600 : (await stat(file)).mode & 0o777;
      const temp = `${file}.aw-${randomBytes(6).toString("hex")}`;
      await writeFile(temp, next, { flag: "wx", mode });
      try {
        await chmod(temp, mode);
        if ((await readText(file)) !== before) continue;
        await rename(temp, file);
        return;
      } finally {
        await rm(temp, { force: true });
      }
    }
    throw new WorkspaceRefusal("the worker's Codex config.toml kept changing; hook trust not written");
  });
}

export function addTrust(home: string, scratchDir: string, trust: HookTrust): Promise<void> {
  return editCodexConfig(home, (before) => addTrustText(before, scratchDir, trust), (config) => hasTrust(config, scratchDir, trust));
}

export function hasAnyTrust(config: TomlTable, scratchDir: string, key: string): boolean {
  const project = table(table(config.projects)[scratchDir]);
  const hook = table(table(table(config.hooks).state)[key]);
  return project.trust_level !== undefined || hook.trusted_hash !== undefined;
}

export async function releaseTrust(home: string, scratchDir: string): Promise<void> {
  const key = expectedTrustKey(scratchDir);
  if (!hasAnyTrust(await readUserConfig(home), scratchDir, key)) return;
  await removeTrust(home, scratchDir, { key, hash: "" });
}

export function removeTrust(home: string, scratchDir: string, trust: HookTrust): Promise<void> {
  return editCodexConfig(
    home,
    (before) => removeTrustText(before, scratchDir, trust),
    (config) => table(table(config.projects)[scratchDir]).trust_level === undefined
      && table(table(table(config.hooks).state)[trust.key]).trusted_hash === undefined,
  );
}


interface Heartbeat {
  tool_name: string;
  tool_input: unknown;
  tool_use_id: string;
  t: number;
}

function canonical(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value as TomlTable).filter(([, v]) => v !== undefined).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonical(v)}`).join(",")}}`;
  }
  return JSON.stringify(value) ?? "null";
}

export function sameCall(raw: unknown, parsed: Record<string, unknown>): boolean {
  const source = table(raw);
  return Object.entries(parsed).every(([key, value]) => value === undefined || canonical(source[key]) === canonical(value));
}

const queues = new Map<string, Promise<unknown>>();

function serialized<T>(key: string, run: () => Promise<T>): Promise<T> {
  const next = (queues.get(key) ?? Promise.resolve()).catch(() => {}).then(run);
  queues.set(key, next);
  void next.finally(() => {
    if (queues.get(key) === next) queues.delete(key);
  }).catch(() => {});
  return next;
}

async function readBeats(dir: string): Promise<{ file: string; beat: Heartbeat | null }[]> {
  const names = await readdir(dir).catch((error: unknown) => {
    if (errorCode(error) === "ENOENT") return [] as string[];
    throw error;
  });
  const out: { file: string; beat: Heartbeat | null }[] = [];
  for (const name of names.filter((n) => n.endsWith(".json")).sort()) {
    const file = path.join(dir, name);
    try {
      out.push({ file, beat: JSON.parse((await readText(file)) ?? "") as Heartbeat });
    } catch {
      out.push({ file, beat: null });
    }
  }
  return out;
}

export function verifyHeartbeat(ctx: Pick<VerifyContext, "scratchDir" | "bindingId" | "toolName" | "input">, now = Date.now()): Promise<void> {
  return serialized(ctx.bindingId, async () => {
    const beats = await readBeats(heartbeatDir(ctx.scratchDir));
    const stale = beats.filter(({ beat }) => beat === null || now - beat.t > HEARTBEAT_MAX_AGE_MS);
    for (const { file } of stale) await rm(file, { force: true });
    const match = beats.find(({ beat }) =>
      beat !== null
      && beat.tool_name === ctx.toolName
      && beat.tool_use_id !== ""
      && now - beat.t <= HEARTBEAT_MAX_AGE_MS
      && sameCall(beat.tool_input, ctx.input));
    if (match === undefined) {
      throw new WorkspaceRefusal(
        "The Codex guard hook did not see this call, so this thread's local tools are not guarded. "
          + "The binding is marked broken; rebind or spawn a new thread.",
      );
    }
    await rm(match.file);
    await appendFile(verifiedFile(ctx.scratchDir), `${JSON.stringify({ tool_name: ctx.toolName, tool_use_id: match.beat!.tool_use_id, t: now })}\n`);
  });
}

async function clearHeartbeats(scratchDir: string): Promise<void> {
  await rm(heartbeatDir(scratchDir), { recursive: true, force: true });
  await mkdir(heartbeatDir(scratchDir), { mode: 0o700 });
  await writeFile(verifiedFile(scratchDir), "");
}


async function assertSupportedLayers(home: string): Promise<void> {
  for (const file of unsupportedLayers(home)) {
    if ((await readText(file)) !== null) {
      throw new WorkspaceRefusal(`Codex config layer ${file} is present on the worker; the Codex profile does not support it`);
    }
  }
}

const trustByBinding = new Map<string, HookTrust>();

async function writeGate(scratchDir: string, result: Record<string, unknown>): Promise<void> {
  await writeFile(gateFile(scratchDir), `${JSON.stringify(result, null, 2)}\n`, { mode: 0o600 });
}

export function createCodexProfile(env: NodeJS.ProcessEnv = process.env): ProviderProfile {
  const home = () => codexHome(env);
  return {
    id: "codex",
    providerIds: ["codex"],
    refusedMachineEnv: CODEX_MACHINE_ENV,
    async prepare(ctx: ProfileContext) {
      if (ctx.model === null) throw new WorkspaceRefusal("the Codex profile needs an explicit model (--model), so the no-fallback check runs on the thread's model");
      await assertSupportedLayers(home());
      const config = await readUserConfig(home());
      await mkdir(path.join(ctx.scratchDir, ".aw"), { recursive: true, mode: 0o700 });
      const mcpNames = mcpServerNames(config);
      await writeProfileFiles(ctx.scratchDir, codexFiles(ctx.scratchDir, ctx.toolNames, mcpNames));
      await clearHeartbeats(ctx.scratchDir);
      const trust = await discoverHookTrust({ launch: resolveCodexLaunch(env), scratchDir: ctx.scratchDir, mcpNames, signal: ctx.signal });
      if (trust.key !== expectedTrustKey(ctx.scratchDir)) {
        throw new WorkspaceRefusal(`Codex reports the guard hook as ${q(trust.key)}, expected ${q(expectedTrustKey(ctx.scratchDir))}`);
      }
      await addTrust(home(), ctx.scratchDir, trust);
      trustByBinding.set(ctx.bindingId, trust);
    },
    async check(ctx: ProfileContext) {
      const trust = trustByBinding.get(ctx.bindingId);
      trustByBinding.delete(ctx.bindingId);
      if (trust === undefined) throw new WorkspaceRefusal("Codex profile check ran without prepare");
      let report: CanaryReport | undefined;
      try {
        const config = await readUserConfig(home());
        report = await runCanary({
          launch: resolveCodexLaunch(env),
          config,
          mcpNames: mcpServerNames(config),
          home: home(),
          scratchDir: ctx.scratchDir,
          trustKey: trust.key,
          model: ctx.model,
          toolNames: ctx.toolNames,
          allowed: codexAllowed(ctx.toolNames),
          signal: ctx.signal,
        });
        if (!hasTrust(await readUserConfig(home()), ctx.scratchDir, trust)) report.failures.push("the hook trust entry vanished from the worker's Codex config");
        await writeGate(ctx.scratchDir, { passed: report.failures.length === 0, at: new Date().toISOString(), ...report });
        if (report.failures.length > 0) {
          throw new WorkspaceRefusal(`Codex no-fallback check failed: ${report.failures.join("; ")}`);
        }
        await clearHeartbeats(ctx.scratchDir);
      } catch (error) {
        if (report === undefined) await writeGate(ctx.scratchDir, { passed: false, at: new Date().toISOString(), error: (error as Error).message }).catch(() => {});
        const rollback = await removeTrust(home(), ctx.scratchDir, trust).then(() => null, (e: unknown) => (e as Error).message);
        if (rollback !== null) {
          const message = `${(error as Error).message}; the hook trust entry could not be removed from the worker's Codex config: ${rollback}`;
          await writeGate(ctx.scratchDir, { passed: false, at: new Date().toISOString(), error: message }).catch(() => {});
          throw new WorkspaceRefusal(message);
        }
        throw error;
      }
    },
    verify: (ctx: VerifyContext) => verifyHeartbeat(ctx),
    release: (ctx: ReleaseContext) => releaseTrust(home(), ctx.scratchDir),
  };
}

export const codexProfile = createCodexProfile();
