import { existsSync } from "node:fs";
import { experimental_execHostFileCallback as execFile } from "@get-bb/plugin-sdk/process";
import { WorkspaceRefusal } from "../confine.js";
import { writeProfileFiles, type ProfileFile } from "./files.js";
import type { ProfileContext, ProviderProfile } from "./types.js";

export function openCodeToolName(name: string): string {
  return `bb-bridge_${name}`;
}

export const ALLOWED_BB_TOOLS = ["bb_update_plan"];

export const REMOVED_PLUGINS = [
  "-opencode.tool.*",
  "-opencode.tools",
  "-opencode.tools.*",
  "-opencode.browser",
  "-opencode.config.command",
];

export const BUILTIN_AGENTS = ["build", "plan", "general", "explore"];

export const OVERRIDING_ENV = [
  "OPENCODE_CONFIG_CONTENT",
  "OPENCODE_CONFIG",
  "OPENCODE_DISABLE_PROJECT_CONFIG",
  "OPENCODE_CONFIG_PROJECT_DISABLE",
];
export const MANAGED_CONFIG_DIR = "/etc/opencode";

export const SUPPORTED_MAJOR = 2;
export const MIN_MINOR = 2;

export function allowedOpenCodeTools(toolNames: readonly string[]): string[] {
  return [...toolNames, ...ALLOWED_BB_TOOLS].map(openCodeToolName);
}

export function openCodeConfig(allowed: readonly string[]) {
  const permission: Record<string, string> = { "*": "deny" };
  for (const name of allowed) permission[name] = "allow";
  return {
    $schema: "https://opencode.ai/config.json",
    plugin: REMOVED_PLUGINS,
    permission,
    agent: Object.fromEntries(BUILTIN_AGENTS.map((id) => [id, { permission }])),
    default_agent: "build",
    snapshots: false,
  };
}

export function guardPlugin(allowed: readonly string[]): string {
  return `// Generated by the account-workers plugin. Blocks every tool call and permission not listed.
const allowed = new Set(${JSON.stringify(allowed)});
const reason = (name) =>
  "Tool " + String(name) + " is disabled in this thread: it would act on the worker machine. " +
  "Use the workspace_* tools, which act on the bound workspace.";
export default {
  id: "account-workers.guard",
  async setup(ctx) {
    await ctx.tool.hook("execute.before", (event) => {
      if (!allowed.has(event.tool)) throw new Error(reason(event.tool));
    });
    await ctx.permission.hook("evaluate", (event) => {
      if (allowed.has(event.action)) return;
      event.effect = "deny";
      event.message = reason(event.action);
    });
  },
};
`;
}

export function openCodeFiles(toolNames: readonly string[]): ProfileFile[] {
  const allowed = allowedOpenCodeTools(toolNames);
  return [
    { path: ".opencode/opencode.json", content: `${JSON.stringify(openCodeConfig(allowed), null, 2)}\n` },
    { path: ".opencode/plugins/aw-guard.js", content: guardPlugin(allowed) },
  ];
}

export function parseVersion(versionOutput: string): { major: number; minor: number } | null {
  const match = /(?:^|\s)v?(\d+)\.(\d+)/.exec(versionOutput.trim());
  return match ? { major: Number(match[1]), minor: Number(match[2]) } : null;
}

function openCodeVersion(signal: AbortSignal): Promise<string> {
  return new Promise((resolve, reject) => {
    execFile("opencode", ["--version"], { encoding: "utf8", timeout: 15_000, signal }, (error, stdout) => {
      if (error) reject(new WorkspaceRefusal(`could not run opencode --version on the worker: ${error.message}`));
      else resolve(stdout);
    });
  });
}

export interface OpenCodeCheckDeps {
  env: NodeJS.ProcessEnv;
  managedConfigExists: () => boolean;
  version: (signal: AbortSignal) => Promise<string>;
}

const realDeps: OpenCodeCheckDeps = {
  env: process.env,
  managedConfigExists: () => existsSync(MANAGED_CONFIG_DIR),
  version: openCodeVersion,
};

export async function checkOpenCode(signal: AbortSignal, deps: OpenCodeCheckDeps = realDeps): Promise<void> {
  const set = OVERRIDING_ENV.filter((name) => (deps.env[name] ?? "") !== "");
  if (set.length > 0) {
    throw new WorkspaceRefusal(`the worker sets ${set.join(", ")}, which overrides or disables the scratch OpenCode config`);
  }
  if (deps.managedConfigExists()) {
    throw new WorkspaceRefusal(`${MANAGED_CONFIG_DIR} exists on the worker; managed OpenCode config loads after the scratch config`);
  }
  const output = await deps.version(signal);
  const version = parseVersion(output);
  if (version === null || version.major !== SUPPORTED_MAJOR || version.minor < MIN_MINOR) {
    throw new WorkspaceRefusal(`OpenCode ${output.trim() || "(no version)"} on the worker; the account-workers profile supports ${SUPPORTED_MAJOR}.${MIN_MINOR} and later ${SUPPORTED_MAJOR}.x only`);
  }
}

export const openCodeProfile: ProviderProfile = {
  id: "opencode",
  providerIds: ["acp-opencode"],
  refusedMachineEnv: OVERRIDING_ENV,
  async prepare(ctx: ProfileContext) {
    await writeProfileFiles(ctx.scratchDir, openCodeFiles(ctx.toolNames));
  },
  check: (ctx) => checkOpenCode(ctx.signal),
};
