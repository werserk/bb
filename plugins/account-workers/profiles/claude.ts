import path from "node:path";
import { WorkspaceRefusal } from "../confine.js";
import { writeProfileFiles } from "./files.js";
import type { ProfileContext, ProviderProfile } from "./types.js";

export function bridgeToolName(name: string): string {
  return `mcp__bb-bridge__${name}`;
}

export const DENIED_NATIVE_TOOLS = [
  "Bash",
  "BashOutput",
  "KillShell",
  "Monitor",
  "TaskStop",
  "Read",
  "Write",
  "Edit",
  "MultiEdit",
  "NotebookEdit",
  "Glob",
  "Grep",
  "LS",
  "WebFetch",
  "Task",
  "Agent",
  "Workflow",
  "SendMessage",
  "ListAgents",
  "EnterWorktree",
  "ExitWorktree",
  "mcp__bb-bridge__update_environment_directory",
];

export const ALLOWED_BUILTIN_TOOLS = ["ToolSearch", "TodoWrite", "mcp__bb-bridge__bb_update_plan"];

export function guardScript(allowed: readonly string[]): string {
  return `// Generated by the account-workers plugin. Blocks every tool not listed.
const allowed = new Set(${JSON.stringify(allowed)});
const block = (reason) => {
  process.stderr.write(reason + "\\n");
  process.exit(2);
};
process.on("uncaughtException", () => block("account-workers guard failed; tool blocked"));
let input = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => (input += chunk));
process.stdin.on("end", () => {
  let name;
  try {
    name = JSON.parse(input).tool_name;
  } catch {
    block("account-workers guard could not read the tool call; tool blocked");
  }
  if (typeof name === "string" && allowed.has(name)) process.exit(0);
  block(
    "Tool " + String(name) + " is disabled in this thread: it would act on the worker machine. " +
      "Use the workspace_* tools, which act on the bound workspace.",
  );
});
`;
}

export function guardLauncher(nodePath: string): string {
  const quoted = `'${nodePath.replaceAll("'", "'\\''")}'`;
  return `#!/bin/sh
# Generated by the account-workers plugin. Fails closed: anything but a clean allow exits 2.
dir=$(dirname "$0")
for n in ${quoted} "$(command -v node 2>/dev/null)"; do
  if [ -n "$n" ] && [ -x "$n" ]; then
    "$n" "$dir/aw-guard.mjs"
    rc=$?
    [ "$rc" -eq 0 ] && exit 0
    echo "account-workers guard: exit $rc; tool blocked" >&2
    exit 2
  fi
done
echo "account-workers guard: node not found; tool blocked" >&2
exit 2
`;
}

export function scratchSettings(scratchDir: string) {
  const launcher = path.join(scratchDir, ".claude", "aw-guard.sh");
  return {
    permissions: { deny: DENIED_NATIVE_TOOLS },
    hooks: {
      PreToolUse: [
        {
          matcher: "*",
          hooks: [{ type: "command", command: `sh '${launcher}'` }],
        },
      ],
    },
  };
}

function nodeForGuard(): string {
  return /^node(\.exe)?$/.test(path.basename(process.execPath)) ? process.execPath : "";
}

export function claudeFiles(scratchDir: string, toolNames: readonly string[], nodePath = nodeForGuard()) {
  if (scratchDir.includes("'")) throw new WorkspaceRefusal("scratch path contains a quote");
  return [
    { path: ".claude/aw-guard.mjs", content: guardScript([...ALLOWED_BUILTIN_TOOLS, ...toolNames.map(bridgeToolName)]) },
    { path: ".claude/aw-guard.sh", content: guardLauncher(nodePath), mode: 0o755 },
    { path: ".claude/settings.local.json", content: `${JSON.stringify(scratchSettings(scratchDir), null, 2)}\n` },
  ];
}

export const claudeProfile: ProviderProfile = {
  id: "claude",
  providerIds: ["claude-code"],
  async prepare(ctx: ProfileContext) {
    await writeProfileFiles(ctx.scratchDir, claudeFiles(ctx.scratchDir, ctx.toolNames));
  },
};
