import { chmod, mkdir, realpath, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import path from "node:path";
import { WorkspaceRefusal } from "./confine.js";

export const DENIED_NATIVE_TOOLS = [
  "Bash",
  "BashOutput",
  "KillShell",
  "Monitor",
  "TaskStop",
  "Read",
  "Write",
  "Edit",
  "MultiEdit",
  "NotebookEdit",
  "Glob",
  "Grep",
  "LS",
  "WebFetch",
  "Task",
  "Agent",
  "Workflow",
  "SendMessage",
  "ListAgents",
  "EnterWorktree",
  "ExitWorktree",
  "mcp__bb-bridge__update_environment_directory",
];

export const ALLOWED_BUILTIN_TOOLS = ["ToolSearch", "TodoWrite"];

export function scratchBase(env: NodeJS.ProcessEnv = process.env): string {
  const state = env.XDG_STATE_HOME && path.isAbsolute(env.XDG_STATE_HOME)
    ? env.XDG_STATE_HOME
    : path.join(homedir(), ".local", "state");
  return path.join(state, "bb-account-workers", "scratch");
}

export function guardScript(allowed: readonly string[]): string {
  return `// Generated by the account-workers plugin. Blocks every tool not listed.
const allowed = new Set(${JSON.stringify(allowed)});
const block = (reason) => {
  process.stderr.write(reason + "\\n");
  process.exit(2);
};
process.on("uncaughtException", () => block("account-workers guard failed; tool blocked"));
let input = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => (input += chunk));
process.stdin.on("end", () => {
  let name;
  try {
    name = JSON.parse(input).tool_name;
  } catch {
    block("account-workers guard could not read the tool call; tool blocked");
  }
  if (typeof name === "string" && allowed.has(name)) process.exit(0);
  block(
    "Tool " + String(name) + " is disabled in this thread: it would act on the worker machine. " +
      "Use the workspace_* tools, which act on the bound workspace.",
  );
});
`;
}

export function guardLauncher(nodePath: string): string {
  const quoted = `'${nodePath.replaceAll("'", "'\\''")}'`;
  return `#!/bin/sh
# Generated by the account-workers plugin. Fails closed when node is missing.
dir=$(dirname "$0")
for n in ${quoted} "$(command -v node 2>/dev/null)"; do
  if [ -n "$n" ] && [ -x "$n" ]; then exec "$n" "$dir/aw-guard.mjs"; fi
done
echo "account-workers guard: node not found; tool blocked" >&2
exit 2
`;
}

export function scratchSettings(scratchDir: string) {
  const launcher = path.join(scratchDir, ".claude", "aw-guard.sh");
  return {
    permissions: { deny: DENIED_NATIVE_TOOLS },
    hooks: {
      PreToolUse: [
        {
          matcher: "*",
          hooks: [{ type: "command", command: `sh '${launcher}'` }],
        },
      ],
    },
  };
}

export async function prepareScratch(input: {
  bindingId: string;
  allowedTools: string[];
}) {
  const dir = path.join(scratchBase(), input.bindingId);
  if (dir.includes("'")) throw new WorkspaceRefusal("scratch path contains a quote");
  await mkdir(path.join(dir, ".claude"), { recursive: true });
  const real = await realpath(dir);
  const claudeDir = path.join(real, ".claude");
  await writeFile(
    path.join(claudeDir, "aw-guard.mjs"),
    guardScript([...ALLOWED_BUILTIN_TOOLS, ...input.allowedTools]),
  );
  const nodePath = /^node(\.exe)?$/.test(path.basename(process.execPath))
    ? process.execPath
    : "";
  await writeFile(path.join(claudeDir, "aw-guard.sh"), guardLauncher(nodePath));
  await chmod(path.join(claudeDir, "aw-guard.sh"), 0o755);
  await writeFile(
    path.join(claudeDir, "settings.local.json"),
    `${JSON.stringify(scratchSettings(real), null, 2)}\n`,
  );
  return { path: real };
}
